/**
 * Generates a randomized ballistic physics profile for tossing a card.
 * @param {number} viewportW - Viewport width
 * @param {number} viewportH - Viewport height
 * @param {Object} card - Card metadata
 * @param {Object} options - Physics overrides (gravity, forceMultiplier)
 */
export function createTossPhysics(viewportW, viewportH, card, options = {}) {
  const forceMultiplier = options.forceMultiplier || 1.0;
  const gravity = (options.gravity || 1080) * (0.92 + Math.random() * 0.16); // 990–1250 px/s²

  // Starting position: below the viewport
  const y0 = viewportH + Math.random() * 140 + 80;

  // Horizontal spread: cards launch from varying positions across central 30%–70% of screen
  const spreadW = Math.min(viewportW * 0.55, 600);
  const centerX = viewportW * 0.5;
  const x0 = centerX + (Math.random() - 0.5) * spreadW - card.width / 2;

  // Target apex: between 12% and 42% of viewport height
  const targetApexY = viewportH * (0.14 + Math.random() * 0.28);
  const deltaApex = Math.max(200, y0 - targetApexY);

  // Exact vertical launch velocity to reach the target apex: vy = -sqrt(2 * g * deltaY)
  // Adjusted by forceMultiplier
  const baseVy = -Math.sqrt(2 * gravity * deltaApex) * forceMultiplier;
  const vy = baseVy * (0.96 + Math.random() * 0.08); // slight jitter

  // Horizontal velocity: slight left/right ballistic arc
  // Slightly bias away from edges toward the center
  const offsetFromCenter = (x0 + card.width / 2) - centerX;
  const inwardBias = -offsetFromCenter * 0.35; // gently nudge back toward center
  const vx = (inwardBias + (Math.random() - 0.5) * 260) * (viewportW < 768 ? 0.6 : 1.0);

  // Rotation: initial subtle tilt and gentle angular velocity
  const initialRotation = (Math.random() - 0.5) * 24; // -12 to +12 deg
  const angularVelocity = (Math.random() - 0.5) * 65; // -32.5 to +32.5 deg/s

  // Scale & depth
  const baseScale = 0.94 + Math.random() * 0.12;
  const zDepth = (Math.random() - 0.5) * 80; // subtle 3D depth

  return {
    x: x0,
    y: y0,
    vx,
    vy,
    gravity,
    rotation: initialRotation,
    angularVelocity,
    scale: baseScale,
    baseScale,
    zDepth,
    zIndex: Math.floor(Math.random() * 40) + 10,
    state: "rising", // "rising" -> "falling" -> "exited"
    targetApexY
  };
}
